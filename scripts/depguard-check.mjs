import {spawnSync} from "node:child_process";
import {existsSync, rmSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const prefix = "github.com/AlexGalhardo/kali-tools/internal/";
const filename = "zz_depguard_violation.go";
const timeout = 300_000;
const maxBuffer = 6 << 20;
const cases = [
  ["internal/domain", "domain", "github.com/gopacket/gopacket", "domain"],
  ["internal/wifi", "wifi", "database/sql", "capabilities"],
  ["internal/app", "app", "os/exec", "application"],
  ["internal/adapter/tools", "tools", prefix + "adapter/cli", "driven-adapters"],
  ["internal/adapter/cli", "cli", prefix + "adapter/storage", "driving-adapters"],
  ["cmd/lab-fixture", "main", "github.com/wailsapp/wails/v2/pkg/runtime", "wails"],
  ["internal/adapter/cli", "cli", prefix + "bootstrap", "bootstrap"],
  ["internal/adapter/storage", "storage", prefix + "porttest", "porttest"],
];
let planted;
function cleanup() {
  if (planted) {
    rmSync(planted);
    planted = undefined;
  }
}
process.on("SIGINT", () => { cleanup(); process.exit(130); });
process.on("SIGTERM", () => { cleanup(); process.exit(143); });
function run(command, args) {
  const result = spawnSync(command, args, {cwd: root, encoding: "utf8", timeout, maxBuffer});
  if (result.error) throw result.error;
  if (result.signal) throw Error(`${command} stopped by ${result.signal}`);
  return {status: result.status, output: result.stdout + result.stderr};
}
try {
  const version = run("golangci-lint", ["--version"]);
  console.log(version.output.trim());
  if (version.status !== 0 || !/\bversion v?2\.15\.0\b/.test(version.output)) {
    throw Error("depguard check requires golangci-lint version 2.15.0 on PATH");
  }
  for (const [directory, pkg, forbidden, rule] of cases) {
    const target = path.join(root, directory, filename);
    // Exclusive creation protects a developer's existing file from cleanup.
    writeFileSync(target, `// Code generated by scripts/depguard-check.mjs; DO NOT COMMIT.\npackage ${pkg}\n\nimport _ "${forbidden}"\n`, {flag: "wx"});
    planted = target;
    try {
      const result = run("golangci-lint", ["run", "--enable-only", "depguard", `./${directory}/`]);
      if (result.status === 0 || !result.output.includes(filename) ||
          !result.output.includes(`list '${rule}'`) || /typecheck|import cycle/i.test(result.output)) {
        throw Error(`Rule ${rule} did not reject its deliberate violation correctly:\n${result.output}`);
      }
      console.log(`PASS ${rule}: rejected ${forbidden}`);
    } finally {
      cleanup();
    }
  }
  const clean = run("golangci-lint", ["run", "--enable-only", "depguard", "./..."]);
  if (clean.status !== 0) throw Error(`Clean tree failed depguard:\n${clean.output}`);
  const status = run("git", ["status", "--porcelain", "--untracked-files=all"]);
  if (status.status !== 0 || status.output.includes(filename) ||
      cases.some(([directory]) => existsSync(path.join(root, directory, filename)))) {
    throw Error(`A deliberate violation remains after cleanup:\n${status.output}`);
  }
  console.log(`depguard check passed: ${cases.length} rules fired`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
} finally {
  cleanup();
}
